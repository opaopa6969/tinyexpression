#!/usr/bin/env node
// Compiles catalog/tinyexpression-catalog.schema.json into a standalone validator module
// (src/generated/catalog-validator.js, not committed) for the Catalog panel (issue #201,
// stage 4). Standalone code needs no `new Function` at run time, so the same bundle also runs
// under the VS Code webview's content security policy.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const schema = JSON.parse(readFileSync(join(here, '..', '..', 'catalog', 'tinyexpression-catalog.schema.json'), 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
const target = join(here, '..', 'src', 'generated', 'catalog-validator.js');
mkdirSync(dirname(target), { recursive: true });
// The ESM output still `require`s ajv's string-length helper (code points); inline it so the
// module has no imports at all.
const code = standaloneCode(ajv, validate)
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', '((text) => [...text].length)');
if (/\brequire\(/.test(code)) throw new Error('standalone validator still requires a module');
writeFileSync(target, `// Generated by scripts/build-validator.mjs from catalog/tinyexpression-catalog.schema.json.\n${code}\n`);
console.log(`wrote ${target.slice(join(here, '..').length + 1)}`);
